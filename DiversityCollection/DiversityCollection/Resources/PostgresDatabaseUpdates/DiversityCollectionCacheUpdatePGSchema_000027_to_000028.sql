--#####################################################################################################################
--######   New column IdentificationSequence in table CacheCollectionSpecimenReference  ###############################
--#####################################################################################################################

ALTER TABLE IF EXISTS "#project#"."CacheCollectionSpecimenReference"
    ADD COLUMN "IdentificationSequence" integer;


--#####################################################################################################################
--######   version  ###################################################################################################
--#####################################################################################################################

DROP FUNCTION "#project#".version();
CREATE OR REPLACE FUNCTION "#project#".version()
  RETURNS integer AS
$BODY$
declare
	v integer;
BEGIN
   SELECT 28 into v;
   RETURN v;
END;
$BODY$
  LANGUAGE plpgsql STABLE
  COST 100;


