INSERT INTO [dbo].[ProjectLicense]
           ([ProjectID]
           ,[DisplayText]
           ,[LicenseURI]
           ,[IPR]
           ,[CopyrightStatement])
SELECT [ProjectID]
      ,'License 1'
      ,[ProjectLicenseURI]
      ,[ProjectCopyright]
      ,[ProjectRights]
  FROM [dbo].[Project]
p where p.ProjectRights <> ''
or p.ProjectCopyright <> ''
or p.ProjectLicenseURI <> ''



